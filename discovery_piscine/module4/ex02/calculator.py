#!/usr/bin/env python3

f_n = int(input("Give me the first number: ").strip())

s_n = int(input("Give me the second number: ").strip())
print("Thank you!")

print(str(f_n) +" + "+ str(s_n) +" = "+ str(f_n + s_n))
print(str(f_n) +" - "+ str(s_n) +" = "+ str(f_n - s_n))
print(str(f_n) +" / "+ str(s_n) +" = "+ str(f_n / s_n))
print(str(f_n) +" * "+ str(s_n) +" = "+ str(f_n * s_n))


